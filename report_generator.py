import json
import os
from datetime import datetime, timezone

def load_json(filepath):
    if not os.path.exists(filepath):
        return {}
    with open(filepath, "r") as f:
        return json.load(f)

def generate_report():
    assets = load_json("current_assets.json")
    drift = load_json("drift_alerts.json")
    compliance = load_json("compliance_score.json")

    domain = compliance.get("domain", "Unknown")
    score = compliance.get("compliance_score", 0)
    grade = compliance.get("grade", "N/A")
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    report_content = f"""# EXECUTIVE ASSET & COMPLIANCE AUDIT REPORT
**Target Domain:** {domain}
**Generated At:** {timestamp}
**Overall Compliance Grade:** {grade} ({score}/100)

---

## 1. COMPLIANCE ASSESSMENT (SOC 2 / ISO 27001)
- **Security Score:** {score}/100
- **Identified Deficiencies:**
"""
    findings = compliance.get("findings", [])
    if findings:
        for finding in findings:
            report_content += f"  - [CRITICAL/HIGH] {finding}\n"
    else:
        report_content += "  - None. All baseline security controls are active.\n"

    report_content += "\n## 2. INFRASTRUCTURE DRIFT STATUS\n"
    if drift.get("has_critical_drift", False):
        report_content += "- **Drift Alert:** DETECTED. Infrastructure has unapproved modifications.\n"
    else:
        report_content += "- **Drift Alert:** SYNCHRONIZED. No drift detected against baseline.\n"

    report_content += "\n## 3. DISCOVERED ASSETS SUMMARY\n"
    dns_records = assets.get("dns_records", {})
    for rtype, records in dns_records.items():
        record_list = ", ".join(records) if records else "None"
        report_content += f"- **{rtype} Records:** {record_list}\n"

    report_content += """
---
*Automated Report generated by Autonomous B2B Asset Pipeline.*
"""

    with open("audit_report.md", "w") as f:
        f.write(report_content)

    print(f"[+] Audit Report successfully created: audit_report.md")

if __name__ == "__main__":
    generate_report()
